#!/usr/bin/env python3
"""Safely reconcile narrow CI-backed statuses into BAKE PRO 4.0.

Does not infer cultural, editorial, council or outreach completion from CI.
"""
import json
import os
from pathlib import Path
from urllib.request import Request, urlopen

ROOT=Path(__file__).resolve().parents[1]
ROADMAP=ROOT/"data/bake-pro-4-roadmap.json"
API="https://api.github.com/repos/deltaowleyes/deltaowleyes.github.io"
WORKFLOW="log-directory-additions.yml"

def get_runs():
    token=os.environ.get("GITHUB_TOKEN")
    if not token:
        raise RuntimeError("GITHUB_TOKEN required")
    req=Request(API+"/actions/workflows/"+WORKFLOW+"/runs?branch=main&per_page=100",
                headers={"Authorization":"Bearer "+token,
                         "Accept":"application/vnd.github+json",
                         "X-GitHub-Api-Version":"2022-11-28"})
    with urlopen(req,timeout=30) as f:
        return json.load(f)["workflow_runs"]

def main():
    doc=json.loads(ROADMAP.read_text(encoding="utf-8"))
    tasks={t["id"]:t for t in doc["tasks"]}
    if doc["schema_version"]!=1 or "S02" not in tasks:
        raise RuntimeError("Unexpected canonical schema")
    task=tasks["S02"]
    if task["status"]=="complete":
        print("S02 already completed; no change")
        return
    # Genuine push on an eligible directory dataset is required; no synthetic
    # listing or forced workflow dispatch is generated by reconciliation.
    runs=get_runs()
    successful=next((r for r in runs if
      r.get("name")=="Record new directory and event listings"
      and r.get("status")=="completed"
      and r.get("conclusion")=="success"
      and r.get("event")=="push"
      and r.get("head_branch")=="main"
      and r.get("created_at","")>"2026-11-05T11:46:43Z"
      and r.get("actor",{}).get("login")!="github-actions[bot]"
      and r.get("html_url","").startswith(
        "https://github.com/deltaowleyes/deltaowleyes.github.io/actions/runs/")
    ),None)
    if not successful:
        print("No conclusive newer successful dataset-triggered logger execution")
        return
    task["status"]="complete"
    task["completed_on"]=successful["created_at"][:10]
    task["notes"]="Genuine dataset-triggered directory logging succeeded, including data validation and commit step."
    evidence={"type":"github_actions","url":successful["html_url"],"result":"success"}
    if not any(x.get("url")==evidence["url"] for x in task.setdefault("evidence",[])):
        task["evidence"].append(evidence)
    doc["updated_at"]=successful["created_at"][:10]
    ROADMAP.write_text(json.dumps(doc,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print("Updated S02 with evidence "+successful["html_url"])

if __name__=="__main__":
    main()
