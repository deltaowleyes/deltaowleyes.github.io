'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const ledger=JSON.parse(fs.readFileSync('data/website-factory-cost-ledger.json','utf8'));
assert.equal(ledger.currency,'CAD');
assert.equal(ledger.development.incremental_cash_cap_cad_exclusive,1);
assert.equal(ledger.production.incremental_generation_and_qa_budget_per_100_options_cad,5);
assert.equal(ledger.production.target_cash_cost_per_option_cad,0.05);
assert.equal(ledger.development.known_billable_actions_initiated_this_bake,0);
assert.equal(ledger.development.known_new_purchases_or_subscriptions_this_bake,0);
assert.equal(ledger.development.unverified_spending_not_assumed_zero,true);
const js=fs.readFileSync('mommamade/v3/site.js','utf8');
assert.ok(!/\bfetch\s*\(|XMLHttpRequest|https:\/\/api\.openai\.com|new\s+WebSocket\b/i.test(js),'No paid API or direct network calls');
const workflow=fs.readFileSync('.github/workflows/mommamade-v3-candidate-qa.yml','utf8');
assert.ok(workflow.includes('ubuntu-latest'),'Only standard public repository runner');
assert.ok(!/\bsecrets\.|OPENAI_API_KEY|ANTHROPIC_API_KEY|AWS_ACCESS_KEY_ID/.test(workflow),'No paid API secrets');
const root=fs.readFileSync('mommamade/index.html','utf8');
assert.ok(root.includes('./v2/'),'V3 must not replace approved V2');
const registry=JSON.parse(fs.readFileSync('data/web-design-projects.json','utf8'));
const p=registry.projects.find(p=>p.id==='momma-made');
assert.equal(p.latest_revision,'v2','V2 still current');
assert.equal(p.revisions.find(r=>r.id==='v3')?.status,'candidate','V3 must remain an unapproved candidate');
console.log('PASS cost and release policy preflight. Account-wide invoices are unverified; this test is NOT a billing audit.');
